# Copies the CPU subset of AOSP's Skia into runtime/third_party/skia (README.md there):
#   python3 -I vendor_skia.py <skia checkout> <files.txt> <headers.txt> <dest>
# files.txt: the translation units; headers.txt: their include closure
# (g++ -MM). Writes sources.cmake with the translation units. Files already
# identical are left untouched, so that a build does not recompile them.
import filecmp
import os
import shutil
import sys

# Variants that Android's build does not use (AVX-512, skcms' AVX paths).
SKIP = {"src/opts/SkOpts_skx.cpp", "modules/skcms/src/skcms_TransformHsw.cc",
        "modules/skcms/src/skcms_TransformSkx.cc"}
HSW = "src/opts/SkOpts_hsw.cpp"

src, files, headers, dest = sys.argv[1:5]
units = [line.strip() for line in open(files) if line.strip() and line.strip() not in SKIP]
deps = [line.strip() for line in open(headers) if line.strip()]
for rel in sorted(set(units) | set(deps) | {"LICENSE"}):
    if rel.startswith("/") or ".." in rel.split("/"):
        raise SystemExit("chemin refusé : " + rel)
    s = os.path.join(src, rel)
    if not os.path.isfile(s):
        raise SystemExit("absent : " + rel)
    d = os.path.join(dest, rel)
    os.makedirs(os.path.dirname(d), exist_ok=True)
    if not (os.path.exists(d) and filecmp.cmp(s, d, shallow=False)):
        shutil.copyfile(s, d)

rest = [u for u in units if u != HSW]
text = ("# Generated by tools/dev/vendor_skia.py (see README.md): Skia's translation units.\n"
        "set(AA_SKIA_SOURCES\n" + "".join(f"  {u}\n" for u in rest) + ")\n"
        "set(AA_SKIA_HSW_SOURCES\n" + (f"  {HSW}\n" if HSW in units else "") + ")\n")
out = os.path.join(dest, "sources.cmake")
if not os.path.exists(out) or open(out).read() != text:
    open(out, "w").write(text)
print(len(units), "unités")
